"""
Standalone Zone Engine core implementation.

Provides spatial geometric relationship tracking between persistent Track objects
(via Ground Point) and Polygon Zones. Manages state machine transitions per track/zone
pair (OUTSIDE -> ENTER -> INSIDE -> EXIT -> OUTSIDE) and generates clean, non-duplicate
Zone Events (TrackEnterZoneEvent, TrackExitZoneEvent, TrackStayZoneEvent).
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from enum import Enum, auto
from typing import TYPE_CHECKING, Optional, Sequence

if TYPE_CHECKING:
    from camera_analytics.models.track import Track
    from camera_analytics.models.zone import Zone

logger = logging.getLogger(__name__)


class TrackZoneState(Enum):
    """Spatial relationship state of a Track relative to a Zone.

    State Transitions::

        OUTSIDE  ──(enters polygon)──> ENTER
        ENTER    ──(next frame inside)─> INSIDE
        INSIDE   ──(exits polygon)──> EXIT
        EXIT     ──(next frame out)─> OUTSIDE
    """

    OUTSIDE = auto()
    ENTER = auto()
    INSIDE = auto()
    EXIT = auto()


class ZoneEventType(Enum):
    """Classification of Zone Engine spatial events."""

    ENTER = auto()
    EXIT = auto()
    STAY = auto()


@dataclass(frozen=True, slots=True)
class ZoneEvent:
    """Event emitted when a track interacts with a spatial Zone.

    Attributes:
        event_type: Type of event (ENTER, EXIT, STAY).
        track_id: Persistent integer Track ID.
        zone_id: Unique string Zone ID.
        zone_name: Human-readable zone name.
        ground_point: (x, y) coordinates of the track's ground point.
        frame_index: Sequential frame index.
        timestamp: Video timestamp in seconds.
        dwell_frames: Number of consecutive frames the track has been inside the zone.
    """

    event_type: ZoneEventType
    track_id: int
    zone_id: str
    zone_name: str
    ground_point: tuple[int, int]
    frame_index: int
    timestamp: float
    dwell_frames: int = 1


@dataclass(slots=True)
class ZoneTrackRecord:
    """Internal tracking record for a single Track relative to a single Zone.

    Attributes:
        track_id: Track ID.
        zone_id: Zone ID.
        state: Current TrackZoneState.
        entry_frame: Frame index when entry occurred.
        entry_timestamp: Timestamp when entry occurred.
        dwell_frames: Total consecutive frames spent inside/entered.
    """

    track_id: int
    zone_id: str
    state: TrackZoneState = TrackZoneState.OUTSIDE
    entry_frame: int = 0
    entry_timestamp: float = 0.0
    dwell_frames: int = 0


@dataclass(slots=True)
class ZoneEngineResult:
    """Output generated by ZoneEngine for a single frame.

    Attributes:
        track_states: Nested dict mapping [track_id][zone_id] -> TrackZoneState.
        events: List of ZoneEvent instances produced during this frame processing.
        zone_occupancy: Dict mapping zone_id -> list of Track objects currently inside/entered.
    """

    track_states: dict[int, dict[str, TrackZoneState]] = field(default_factory=dict)
    events: list[ZoneEvent] = field(default_factory=list)
    zone_occupancy: dict[str, list[Track]] = field(default_factory=dict)


class ZoneEngine:
    """Standalone spatial engine for Polygon Zones and Track spatial relationships.

    Maintains state records across frames to emit non-duplicate ENTER/EXIT/STAY events.

    Example::

        engine = ZoneEngine()

        # Each frame:
        result = engine.process(tracks, zones, frame_index=10, timestamp=0.33)

        for event in result.events:
            if event.event_type == ZoneEventType.ENTER:
                logger.info("Track #%d entered zone '%s'", event.track_id, event.zone_name)
    """

    def __init__(self) -> None:
        # Records map: (track_id, zone_id) -> ZoneTrackRecord
        self._records: dict[tuple[int, str], ZoneTrackRecord] = {}

    def process(
        self,
        tracks: Sequence[Track],
        zones: Sequence[Zone],
        frame_index: int = 0,
        timestamp: float = 0.0,
    ) -> ZoneEngineResult:
        """Process active tracks against active zones and return spatial states & events.

        Args:
            tracks: Active Track objects in current frame.
            zones: Configured Zone objects for the camera.
            frame_index: Sequential frame number.
            timestamp: Video timestamp in seconds.

        Returns:
            ZoneEngineResult containing track states, emitted events, and occupancy mapping.
        """
        events: list[ZoneEvent] = []
        track_states: dict[int, dict[str, TrackZoneState]] = {}
        zone_occupancy: dict[str, list[Track]] = {z.zone_id: [] for z in zones}

        active_track_ids = {t.track_id for t in tracks}
        valid_zones = [z for z in zones if z.is_valid]

        for track in tracks:
            t_id = track.track_id
            ground_x, ground_y = track.detection.ground_point
            track_states[t_id] = {}

            for zone in valid_zones:
                z_id = zone.zone_id
                key = (t_id, z_id)

                # Test polygon containment using ground point
                is_inside = zone.contains_point(int(ground_x), int(ground_y))

                # Fetch or create record
                record = self._records.get(key)
                if record is None:
                    record = ZoneTrackRecord(track_id=t_id, zone_id=z_id)
                    self._records[key] = record

                prev_state = record.state
                new_state: TrackZoneState

                if is_inside:
                    zone_occupancy[z_id].append(track)
                    if prev_state in (TrackZoneState.OUTSIDE, TrackZoneState.EXIT):
                        new_state = TrackZoneState.ENTER
                        record.entry_frame = frame_index
                        record.entry_timestamp = timestamp
                        record.dwell_frames = 1

                        event = ZoneEvent(
                            event_type=ZoneEventType.ENTER,
                            track_id=t_id,
                            zone_id=z_id,
                            zone_name=zone.name,
                            ground_point=(int(ground_x), int(ground_y)),
                            frame_index=frame_index,
                            timestamp=timestamp,
                            dwell_frames=1,
                        )
                        events.append(event)
                        logger.debug("ZoneEvent [ENTER]: Track #%d -> Zone '%s'", t_id, zone.name)

                    else:  # prev_state in (ENTER, INSIDE)
                        new_state = TrackZoneState.INSIDE
                        record.dwell_frames += 1

                        event = ZoneEvent(
                            event_type=ZoneEventType.STAY,
                            track_id=t_id,
                            zone_id=z_id,
                            zone_name=zone.name,
                            ground_point=(int(ground_x), int(ground_y)),
                            frame_index=frame_index,
                            timestamp=timestamp,
                            dwell_frames=record.dwell_frames,
                        )
                        events.append(event)

                else:  # is_inside == False
                    if prev_state in (TrackZoneState.ENTER, TrackZoneState.INSIDE):
                        new_state = TrackZoneState.EXIT
                        event = ZoneEvent(
                            event_type=ZoneEventType.EXIT,
                            track_id=t_id,
                            zone_id=z_id,
                            zone_name=zone.name,
                            ground_point=(int(ground_x), int(ground_y)),
                            frame_index=frame_index,
                            timestamp=timestamp,
                            dwell_frames=record.dwell_frames,
                        )
                        events.append(event)
                        logger.debug("ZoneEvent [EXIT]: Track #%d <- Zone '%s'", t_id, zone.name)
                        record.dwell_frames = 0
                    else:
                        new_state = TrackZoneState.OUTSIDE
                        record.dwell_frames = 0

                record.state = new_state
                track_states[t_id][z_id] = new_state

        # Cleanup records for tracks that were removed/inactive
        dead_keys = [
            k for k in self._records.keys() if k[0] not in active_track_ids
        ]
        for dk in dead_keys:
            old_rec = self._records.pop(dk, None)
            if old_rec and old_rec.state in (TrackZoneState.ENTER, TrackZoneState.INSIDE):
                # Emit EXIT event for disappearing track
                zone_obj = next((z for z in valid_zones if z.zone_id == dk[1]), None)
                z_name = zone_obj.name if zone_obj else dk[1]
                events.append(
                    ZoneEvent(
                        event_type=ZoneEventType.EXIT,
                        track_id=dk[0],
                        zone_id=dk[1],
                        zone_name=z_name,
                        ground_point=(0, 0),
                        frame_index=frame_index,
                        timestamp=timestamp,
                        dwell_frames=old_rec.dwell_frames,
                    )
                )

        return ZoneEngineResult(
            track_states=track_states,
            events=events,
            zone_occupancy=zone_occupancy,
        )

    def reset(self) -> None:
        """Reset internal zone engine tracking state."""
        self._records.clear()
        logger.info("ZoneEngine reset")
